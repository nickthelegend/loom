import fs from 'node:fs';
import path from 'node:path';
import { JSDOM, VirtualConsole } from 'jsdom';
import WebSocket from 'ws';
import { afterAll, beforeAll, expect, it } from 'vitest';
import { LoomDaemon } from '../src/daemon/server.js';
import { DaemonClient } from '../src/daemon/client.js';
import { readDaemonConfig } from '../src/core/registry.js';
import { APP_HTML } from '../src/daemon/app-page.js';
import type { ProjectRuntime } from '../src/daemon/runtime.js';
import { tmpDir, makeProjectDir, waitUntil } from './helpers.js';
let daemon: LoomDaemon, base: string, token: string, projectId: string, rt: ProjectRuntime;
let dom: JSDOM | undefined;
const errors: string[] = [], sockets: WebSocket[] = [];
let closed = false;
beforeAll(async () => {
  process.env.LOOM_HOME = tmpDir('r4-dom'); process.env.LOOM_NO_NOTIFY = '1';
  daemon = new LoomDaemon({ host: '127.0.0.1', port: 0 }); const address = await daemon.listen(); base = `http://${address.host}:${address.port}`;
  const client = new DaemonClient(readDaemonConfig()!); const dir = makeProjectDir({ name: 'insight-dom' }); fs.writeFileSync(path.join(dir, 'sample.txt'), 'Hot spot contents'); projectId = (await client.addProject(dir)).project.id;
  const minted = await client.newPairingToken();
  token = ((await (await fetch(base + '/api/pair/claim', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ token: minted.token, name: 'browser' }) })).json()) as { clientToken: string }).clientToken;
  rt = await (daemon as unknown as { runtime(id: string): Promise<ProjectRuntime> }).runtime(projectId);
  rt.log.append({ kind: 'status', agentId: 'plannerbot', payload: { state: 'turn_started' } });
  rt.log.append({ kind: 'tool_call', agentId: 'plannerbot', payload: { tool: '<img src=x onerror=alert(1)>', ok: false, durationMs: 120 } });
  rt.log.append({ kind: 'file_edit', agentId: 'plannerbot', payload: { path: 'sample.txt' } });
  rt.log.append({ kind: 'run_complete', agentId: 'plannerbot', payload: { model: 'echo-1', durationMs: 1000 } });
  rt.log.append({ kind: 'approval', agentId: 'plannerbot', payload: { phase: 'requested', approvalId: 'a', tool: 'shell', input: { command: 'npm test' } } });
  rt.log.append({ kind: 'approval', agentId: 'plannerbot', payload: { phase: 'decided', approvalId: 'a', by: 'phone', behavior: 'allow' } });
  rt.log.append({ kind: 'approval', agentId: 'plannerbot', payload: { phase: 'requested', approvalId: 'read', tool: 'Read', input: { command: 'sample.txt' } } });
  rt.log.append({ kind: 'error', agentId: 'execbot', payload: { message: 'Request 42 failed' } });
});
afterAll(async () => { closed = true; for (const s of sockets) { s.on('error', () => {}); s.terminate(); } dom?.window.close(); await daemon.close(); });
function mount() {
  const vc = new VirtualConsole(); vc.on('jsdomError', e => errors.push(e.message)); vc.on('error', e => errors.push(String(e)));
  dom = new JSDOM(APP_HTML, { url: `${base}/app#p/${projectId}`, runScripts: 'dangerously', pretendToBeVisual: true, virtualConsole: vc,
    beforeParse(window) {
      window.scrollTo = () => {}; window.HTMLElement.prototype.scrollTo = () => {}; window.HTMLElement.prototype.scrollIntoView = () => {};
      window.ResizeObserver = class { observe() {} unobserve() {} disconnect() {} } as any;
      window.matchMedia = ((q: string) => ({ matches: /min-width/.test(q), media: q, onchange: null, addListener() {}, removeListener() {}, addEventListener() {}, removeEventListener() {}, dispatchEvent: () => false })) as any;
      window.fetch = ((input: string, init?: RequestInit) => {
        if (closed) return new Promise(() => {});
        if (new URL(String(input), base).pathname.endsWith('/agents/models')) return Promise.resolve(new Response(JSON.stringify({ models: ['echo-1'] })));
        return fetch(new URL(String(input), base), init).then(r => closed ? new Promise(() => {}) : r);
      }) as any;
      window.WebSocket = class extends WebSocket { constructor(url: string, protocols?: string | string[]) { super(url, protocols); sockets.push(this); } } as any;
      window.localStorage.setItem('loomClientToken', token); window.localStorage.setItem('loomDevMode', '1'); window.confirm = () => true;
    } });
  return dom.window.document;
}
it('renders live API data, escapes strings, queries and saves filters, and manages alerts and allow suggestions', async () => {
  const doc = mount();
  await waitUntil(() => !!doc.querySelector('.tab[data-tab="observatory"]'));
  (doc.querySelector('.tab[data-tab="observatory"]') as HTMLElement).click();
  await waitUntil(() => !!doc.querySelector('[data-report] table'));
  const root = () => doc.querySelector('.r4insights')!;
  expect(root().textContent).toContain('<img src=x onerror=alert(1)>'); expect(root().querySelector('img')).toBeNull();
  expect(root().textContent).toContain('Latency by model'); expect(root().querySelector('meter')).toBeTruthy();
  expect(root().textContent).toContain('Failure groups'); expect(root().querySelector('a[href*="/m/"]')).toBeTruthy();
  (root().querySelector('[data-file]') as HTMLElement).click();
  await waitUntil(() => doc.body.textContent?.includes('Hot spot contents') === true);
  expect(root().textContent).toContain('Agent hours'); expect(root().textContent).toContain('previous');
  const form = root().querySelector('[data-filter]') as HTMLFormElement;
  (form.elements.namedItem('type') as HTMLInputElement).value = 'tool_call';
  (form.elements.namedItem('agent') as HTMLInputElement).value = 'plannerbot';
  form.dispatchEvent(new dom!.window.Event('submit', { bubbles: true, cancelable: true }));
  await waitUntil(() => root().querySelectorAll('[data-events] tbody tr').length === 1 && root().querySelector('[data-events] tbody')?.textContent?.includes('tool_call') === true);
  expect(root().querySelector('[data-events] tbody')?.textContent).not.toContain('run_complete');
  (root().querySelector('[data-save]') as HTMLElement).click();
  expect(JSON.parse(dom!.window.localStorage.getItem(`loom:r4:events:${projectId}`)!)[0]).toMatchObject({ type: 'tool_call', agent: 'plannerbot' });
  const saved = root().querySelector('[data-saved]') as HTMLSelectElement;
  (form.elements.namedItem('type') as HTMLInputElement).value = ''; saved.value = '0'; saved.dispatchEvent(new dom!.window.Event('change', { bubbles: true }));
  expect((form.elements.namedItem('type') as HTMLInputElement).value).toBe('tool_call');
  expect(root().textContent).toContain('Shell: review each command');
  expect(root().querySelectorAll('[data-allow]')).toHaveLength(1);
  const confirmations: string[] = [];
  dom!.window.confirm = message => { confirmations.push(String(message)); return false; };
  (root().querySelector('[data-allow]') as HTMLElement).click();
  expect(confirmations).toEqual(['Allow every Read call in this project without asking?']);
  expect(rt.safetyPolicy().allow).not.toContain('Read');
  expect((root().querySelector('[data-allow]') as HTMLButtonElement).disabled).toBe(false);
  dom!.window.confirm = () => true;
  (root().querySelector('[data-allow]') as HTMLElement).click();
  await waitUntil(() => rt.safetyPolicy().allow.includes('Read'));
  expect(rt.safetyPolicy().allow).not.toContain('shell');
  const alertForm = root().querySelector('[data-add-alert]') as HTMLFormElement;
  (alertForm.elements.namedItem('expression') as HTMLInputElement).value = 'queue_depth > 3';
  alertForm.dispatchEvent(new dom!.window.Event('submit', { bubbles: true, cancelable: true }));
  await waitUntil(() => !!root().querySelector('[data-pause]'));
  (root().querySelector('[data-pause]') as HTMLElement).click();
  await waitUntil(() => root().querySelector('[data-pause]')?.textContent === 'Resume');
  (root().querySelector('[data-test]') as HTMLElement).click();
  await waitUntil(() => root().querySelector('[data-alert-status]')?.textContent?.includes('Test notification sent') === true);
  expect(errors).toEqual([]);
}, 40000);
